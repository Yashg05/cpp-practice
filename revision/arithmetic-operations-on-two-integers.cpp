#include<iostream>
using namespace std;

int main()
{
    int a;
    int b;

    cin >> a;
    cin >> b;

    cout << "The sum of the integers is: " 
    << a+b << endl;
    cout << "The product of the integers is: " 
    << a*b << endl;
    cout << "The difference of the integers is: " 
    << a-b << endl;
    cout << "The quotient of the integers is: "
    << a/b << endl;
    cout << "The remainder recieved by dividing both is: "
    << a%b << endl;
    
    return 0;
}
